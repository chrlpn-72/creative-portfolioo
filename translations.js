  try {
    const saved = localStorage.getItem("charlie-portfolio-language");
    if (saved === "fr" || saved === "en") language = saved;
  } catch {
    // Language switching remains available for this page view.
  }

  const originalTexts = new WeakMap();
  const originalAttributes = new WeakMap();
  const t = (text, lang = language) => {
    if (lang !== "fr") return text;
    return projectFrench[text] || french[text] || text;
  };

  const translateDocument = () => {
    document.documentElement.lang = language;
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    while (walker.nextNode()) {
      const node = walker.currentNode;
      if (!originalTexts.has(node)) originalTexts.set(node, node.nodeValue);
      const original = originalTexts.get(node);
      const trimmed = original.trim();
      if (!trimmed) continue;
      const leading = original.match(/^\s*/)?.[0] || "";
      const trailing = original.match(/\s*$/)?.[0] || "";
      node.nodeValue = `${leading}${t(trimmed)}${trailing}`;
    }

    document.querySelectorAll("[aria-label], [placeholder], [title], [data-cursor]").forEach((element) => {
      ["aria-label", "placeholder", "title", "data-cursor"].forEach((name) => {
        if (!element.hasAttribute(name)) return;
        let values = originalAttributes.get(element);
        if (!values) {
          values = new Map();
          originalAttributes.set(element, values);
        }
        if (!values.has(name)) values.set(name, element.getAttribute(name));
        element.setAttribute(name, t(values.get(name)));
      });
    });

    document.querySelectorAll('meta[name="description"], meta[property="og:title"], meta[property="og:description"]').forEach((meta) => {
      const original = meta.dataset.originalContent || meta.content;
      meta.dataset.originalContent = original;
      meta.content = t(original);
    });
    const titleOriginal = document.querySelector("title")?.dataset.originalTitle || document.title;
    const titleElement = document.querySelector("title");
    if (titleElement) {
      titleElement.dataset.originalTitle = titleOriginal;
      document.title = t(titleOriginal);
    }
    document.querySelectorAll(".assistant-launcher").forEach((launcher) => launcher.setAttribute("aria-label", language === "fr" ? "Ouvrir l’assistant Charlie" : "Open Ask Charlie assistant"));
  };

  const switcher = document.createElement("div");
  switcher.className = "language-switch";
  switcher.setAttribute("role", "group");
  switcher.setAttribute("aria-label", "Choose language");
  switcher.innerHTML = '<button type="button" data-language="fr">FR</button><span aria-hidden="true">·</span><button type="button" data-language="en">EN</button>';

  const updateSwitchers = () => {
    document.querySelectorAll(".language-switch button").forEach((option) => {
      const selected = option.dataset.language === language;
      option.classList.toggle("is-active", selected);
      option.setAttribute("aria-pressed", String(selected));
    });
  };

  switcher.addEventListener("click", (event) => {
    const button = event.target.closest("[data-language]");
    if (!button || button.dataset.language === language) return;
    language = button.dataset.language;
    try {
      localStorage.setItem("charlie-portfolio-language", language);
    } catch {
      // Keep the selected language for this page view.
    }
    updateSwitchers();
    document.documentElement.classList.add("language-changing");
    translateDocument();
    window.dispatchEvent(new CustomEvent("portfolio-languagechange", { detail: { language } }));
    window.setTimeout(() => document.documentElement.classList.remove("language-changing"), 150);
  });

  window.portfolioI18n = {
    get language() { return language; },
    t,
    refresh: translateDocument,
    init() {
      document.querySelector(".desktop-nav")?.prepend(switcher);
      updateSwitchers();
      translateDocument();
    }
  };
